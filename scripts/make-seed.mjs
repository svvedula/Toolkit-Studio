// Generates supabase/seed.sql from src/data/catalog.ts so the database and the
// shipped catalog never drift. Run: npm run seed:sql
import { writeFileSync } from 'node:fs';
import { build } from 'vite';

const out = await build({
  logLevel: 'silent',
  build: { write: false, ssr: true, lib: { entry: 'src/data/catalog.ts', formats: ['es'], fileName: 'catalog' }, rollupOptions: { external: [] } },
});
const code = out[0].output[0].code;
const tmp = new URL('../node_modules/.catalog.mjs', import.meta.url);
writeFileSync(tmp, code);
const { TOOLS } = await import(tmp.href);

const q = s => `'${String(s).replace(/'/g, "''")}'`;
const rows = TOOLS.map(t => `(${[q(t.slug), q(t.name), q(t.category), q(t.access), q(t.skill), q(t.url), t.embeddable, q(t.description), `array[${t.tags.map(q).join(',')}]::text[]`].join(', ')})`);
const sql = `-- generated by scripts/make-seed.mjs — do not edit by hand
insert into public.tools (slug, name, category, access_tier, skill_tier, url, embeddable, description, tags) values
${rows.join(',\n')}
on conflict (slug) do update set name = excluded.name, category = excluded.category, access_tier = excluded.access_tier,
  skill_tier = excluded.skill_tier, url = excluded.url, embeddable = excluded.embeddable, description = excluded.description, tags = excluded.tags;
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote ${TOOLS.length} tools to supabase/seed.sql`);
